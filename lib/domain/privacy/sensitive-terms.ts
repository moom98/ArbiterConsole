import { dual, type DualPattern } from "./normalize";

/** 機微な内容の分類（A.1） */
export type SensitiveClass =
  | "fair-play"
  | "health"
  | "harassment"
  | "crime"
  | "religion"
  | "family-minors"
  | "english";

export interface SensitiveExpression {
  class: SensitiveClass;
  pattern: DualPattern;
}

const expr = (
  cls: SensitiveClass,
  source: string,
  options?: { flags?: string; unfoldedOnly?: boolean }
): SensitiveExpression => ({ class: cls, pattern: dual(source, options) });

