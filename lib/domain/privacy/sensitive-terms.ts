/**
 * A.2 文脈で判断する表現（L3）。出現ごとに判断する:
 * - sensitive の一致が出現に重なれば blocked
 * - benign の一致が出現を覆えば clear
 * - それ以外は uncertain（ローカルで処理。安全とはみなさない）
 */
export interface ContextExpression {
  id: string;
  triggers: DualPattern;
  sensitive: readonly DualPattern[];
  benign: readonly DualPattern[];
}

const entry = (
  id: string,
  triggers: string,
  sensitive: string[] = [],
  benign: string[] = []
): ContextExpression => ({
  id,
  triggers: dual(triggers),
  sensitive: sensitive.map((s) => dual(s)),
  benign: benign.map((s) => dual(s)),
});

